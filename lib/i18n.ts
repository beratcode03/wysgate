export function translate(language: Language, key: string, values: Record<string, string | number> = {}) {
  const text = messages[language][key] ?? messages.tr[key] ?? key;
  return Object.entries(values).reduce((result, [name, value]) => result.replace(`{${name}}`, String(value)), text);
}

export function categoryLabel(language: Language, category: string) {
  return categories[category]?.[language] ?? category;
}

export function useI18n() {
  const { settings } = useVault();
  const language = settings.language;
  return {
    language,
    t: (key: string, values?: Record<string, string | number>) => translate(language, key, values),
    categoryLabel: (category: string) => categoryLabel(language, category),
  };
}